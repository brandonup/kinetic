"""
LLM judge for Active Memory proposal quality eval (KIN-328).

Scores each proposal 0–2:
  0 = wrong / irrelevant / hallucinated / verbatim quote
  1 = acceptable — vaguely relevant but imprecise or redundant
  2 = good — specific, durable, directly actionable for future AI collaboration

Judge model: gpt-4o (platform key recommended; or user BYOK key).
"""

import json
import sys

JUDGE_PROMPT_TEMPLATE = """You are evaluating a memory proposal generated by an AI from a conversation.

The memory proposal system is designed to capture facts, preferences, decisions, or working patterns
that would change how an AI assistant collaborates with this person in future sessions.

**Conversation:**
{conversation}

**Proposed memory entry:**
"{proposal}"

**Score this proposal 0, 1, or 2:**
- 2 = GOOD: Specific, durable, factually grounded in the conversation, directly useful for future AI collaboration.
  Would meaningfully change how an assistant responds to this person.
- 1 = ACCEPTABLE: Vaguely relevant but imprecise, too generic, or somewhat redundant with obvious context.
  Not wrong, but marginal value.
- 0 = WRONG: Irrelevant, hallucinated (not in the conversation), a verbatim quote, or a summary rather than a memory.

Respond with ONLY a JSON object: {{"score": <0|1|2>, "reason": "<one sentence>"}}"""


def format_conversation(messages: list) -> str:
    lines = []
    for m in messages:
        role = "User" if m["role"] == "user" else "Assistant"
        lines.append(f"{role}: {m['content']}")
    return "\n".join(lines)


def judge_proposal(
    proposal: str,
    messages: list,
    api_key: str,
    model: str = "gpt-4o",
) -> dict:
    """
    Score a single proposal using an LLM judge.

    Returns: {"score": int, "reason": str}
    """
    # Import here so the module loads without requiring app context
    sys.path.insert(0, str(__import__("pathlib").Path(__file__).parent.parent.parent / "packages" / "api"))
    from app.services.llm_client import call_llm

    conversation_text = format_conversation(messages)
    prompt = JUDGE_PROMPT_TEMPLATE.format(
        conversation=conversation_text,
        proposal=proposal,
    )

    raw = call_llm(
        messages=[{"role": "user", "content": prompt}],
        model=model,
        api_key=api_key,
        max_tokens=150,
        timeout=20,
    ).strip()

    # Strip markdown fences if present
    import re
    cleaned = re.sub(r"```(?:json)?\s*|\s*```", "", raw).strip()
    data = json.loads(cleaned)
    return {"score": int(data["score"]), "reason": data.get("reason", "")}


def judge_conversation(
    conversation: dict,
    proposals: list,
    api_key: str,
    model: str = "gpt-4o",
) -> dict:
    """
    Score all proposals generated for a single conversation.

    Returns summary dict with per-proposal scores + mean + pass/fail.
    """
    if not proposals:
        # Expected sparse — empty proposals are acceptable for task/grammar conversations
        is_ok = conversation.get("expected_sparse", False)
        return {
            "conversation_id": conversation["id"],
            "label": conversation["label"],
            "category": conversation["category"],
            "proposals": [],
            "mean_score": None,
            "proposal_count": 0,
            "pass": is_ok,
            "note": "empty proposals — OK for sparse category" if is_ok else "FAIL: no proposals generated for substantive conversation",
        }

    scored = []
    for p in proposals:
        result = judge_proposal(p, conversation["messages"], api_key, model)
        scored.append({"proposal": p, "score": result["score"], "reason": result["reason"]})

    scores = [s["score"] for s in scored]
    mean = sum(scores) / len(scores)

    # Check for sparse-category false positives
    if conversation.get("expected_sparse") and len(proposals) > 2:
        note = f"WARNING: {len(proposals)} proposals generated for a task-only conversation (expected 0-2)"
    else:
        note = ""

    return {
        "conversation_id": conversation["id"],
        "label": conversation["label"],
        "category": conversation["category"],
        "proposals": scored,
        "mean_score": round(mean, 2),
        "proposal_count": len(proposals),
        "pass": mean >= 1.5,
        "note": note,
    }
